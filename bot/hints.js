'use strict';
/**
 * Подсказки игроку — «что у вас на руках», «шанс выиграть», советы наставника.
 *
 * Выключены у всех (владелец, 2026-10-20: «пока мы их полностью убираем»;
 * позже — включаемый пункт в настройках). Выключатель один и серверный:
 * выключенная подсказка не уходит на телефон вообще, а не просто прячется.
 *
 *   hints.on = true  — вернуть (так делает тест и будущая настройка);
 *   переменная окружения HINTS=1 — то же на запуске.
 *
 * Что считается подсказкой: имя собранной руки у игрока на столе
 * (`me.handName` в покере), совет и «шанс выиграть» наставника школы. Что НЕ
 * считается: правила и цели уроков, оценка урока после раздачи, подсветка
 * возможных ходов и пояснения на экранах, названия рук на вскрытии.
 */
export const hints = { on: process.env.HINTS === '1' };
