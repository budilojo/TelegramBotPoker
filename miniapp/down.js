/**
 * Что видит игрок, пока идёт обслуживание.
 *
 * Не ошибка и не пустой стол: человек открыл приложение, а игра стоит — и он
 * должен понять, что стол никуда не делся и его время на ход не тратится.
 * Поэтому здесь текст владельца, а не «что-то пошло не так», и ни одной
 * кнопки, которая обещала бы то, чего сейчас нельзя.
 */
import { $app, h } from './ui.js';
import { bus, send, net } from './net.js';

let state = null;

export function onState(s) {
  state = s;
  bus.render();
}

export function render() {
  const s = state;
  $app.append(h('div.lobby.down',
    h('div.down-mark', '⏸'),
    h('h1', 'Идёт обслуживание'),
    h('div.down-text', s.text || 'Скоро вернёмся.'),
    h('div.box.down-box',
      h('div.down-row', h('span', '🃏'), h('span', 'Столы на месте — партия продолжится с той же карты.')),
      h('div.down-row', h('span', '⏱'), h('span', 'Время на ход не тратится: часы остановлены.')),
      h('div.down-row', h('span', '🔔'), h('span', 'Когда всё закончится, экран обновится сам.'))),
    h('div.hint', 'Можно закрыть приложение — ничего не пропадёт.'),
  ));
  // Связь есть, просто игра стоит: отдельная плашка «нет связи» тут врала бы.
  if (!net.connected) $app.append(h('div.conn', 'Нет связи — переподключаемся…'));
}

/** Экран сам спрашивает состояние: обслуживание снимут — страница вернётся к игре. */
setInterval(() => {
  if (state) send({ t: 'refresh' }, { lock: false });
}, 15_000);
